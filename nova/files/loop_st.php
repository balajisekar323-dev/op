2(a). For
<?php
for ($i = 0; $i < 5; $i++) {
$product = 10 * $i;
echo "The Product of 10*$i = $product.\n";
}
?>
2(b). Foreach
<?php
$animal_List = array("Lion", "dog", "wolf", "leopard", "tiger");
foreach ($animal_List as $array_List) {
echo $array_List . "\n";
}
?>
2(c). While
<?php
$i = 1;
echo "The Number from 1 to 10 \n";
while ($i <= 10) {
echo $i . " ";
$i++;
}
?>
